"""Reconstruct the final clustered Toronto dataset from the notebook's saved
cell outputs + Geospatial_Coordinates.csv.

The notebook never persisted `toronto_merged`, and it cannot be regenerated by
re-running (Wikipedia + Foursquare are network-blocked, the Foursquare creds
were never committed, and the v2 endpoint is retired). However every field of
the final result survives in the executed cell outputs:

  * cell 23  -> the 38 neighborhoods in dataset (index) order
  * cell 36  -> per-neighborhood top-10 venues with frequencies
  * cells 46/48/50/51/52 -> each neighborhood's borough + KMeans cluster label
  * Geospatial_Coordinates.csv -> postcode -> (lat, long)

We rejoin them on the dataframe row index and write toronto_final.csv.
"""

import json
import re
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NB = ROOT / "Segmenting and Clustering Toronto.ipynb"
GEO = ROOT / "Geospatial_Coordinates.csv"
OUT = Path(__file__).resolve().parent / "toronto_final.csv"
OUT_JSON = Path(__file__).resolve().parent / "toronto_data.json"

# Toronto-borough postal codes in the dataset's sorted order (index 0..37).
# This is the stable IBM/Coursera source data; the first five are cross-checked
# below against cell 42's head() output, and lat/long come straight from the CSV.
POSTCODES = [
    "M4E", "M4K", "M4L", "M4M", "M4N", "M4P", "M4R", "M4S", "M4T", "M4V",
    "M4W", "M4X", "M4Y", "M5A", "M5B", "M5C", "M5E", "M5G", "M5H", "M5J",
    "M5K", "M5L", "M5N", "M5P", "M5R", "M5S", "M5T", "M5V", "M5W", "M5X",
    "M6G", "M6H", "M6J", "M6K", "M6P", "M6R", "M6S", "M7Y",
]

CLUSTER_CELLS = {46: 0, 48: 1, 50: 2, 51: 3, 52: 4}


def cell_text(cell):
    """Join a cell's output text whether it is a stream or a data result."""
    chunks = []
    for out in cell.get("outputs", []):
        if "text" in out:
            chunks.append("".join(out["text"]))
        data = out.get("data", {})
        if "text/plain" in data:
            chunks.append("".join(data["text/plain"]))
    return "\n".join(chunks)


def load_notebook():
    return json.loads(NB.read_text())["cells"]


def parse_neighborhood_order(cells):
    """cell 23 prints one neighborhood name per line, in index order."""
    text = cell_text(cells[23])
    names = [ln.strip() for ln in text.splitlines() if ln.strip()]
    assert len(names) == 38, f"expected 38 neighborhoods, got {len(names)}"
    return names


def parse_top_venues(cells):
    """cell 36 prints '----Name----' headers followed by a venue/freq table."""
    text = cell_text(cells[36])
    blocks = re.split(r"-{4}(.+?)-{4}", text)
    venues = {}
    # blocks = ['', name1, body1, name2, body2, ...]
    for i in range(1, len(blocks), 2):
        name = blocks[i].strip()
        body = blocks[i + 1]
        rows = []
        for ln in body.splitlines():
            m = re.match(r"\s*\d+\s+(.+?)\s+([01]\.\d+)\s*$", ln)
            if m:
                rows.append((m.group(1).strip(), float(m.group(2))))
        venues[name] = rows[:10]
    assert len(venues) == 38, f"expected 38 venue blocks, got {len(venues)}"
    return venues


def parse_clusters(cells):
    """Each cluster cell lists the row indices belonging to that cluster, plus
    the borough. Lines look like: '0       East Toronto               0  ...'"""
    idx_cluster, idx_borough = {}, {}
    for cell_no, label in CLUSTER_CELLS.items():
        text = cell_text(cells[cell_no])
        for ln in text.splitlines():
            m = re.match(r"^(\d+)\s+(.*?Toronto)\s+\d\b", ln)
            if m:
                idx = int(m.group(1))
                idx_cluster[idx] = label
                idx_borough[idx] = m.group(2).strip()
    assert len(idx_cluster) == 38, f"expected 38 cluster rows, got {len(idx_cluster)}"
    return idx_cluster, idx_borough


def load_geo():
    geo = {}
    with open(GEO, newline="") as f:
        for row in csv.DictReader(f):
            geo[row["Postal Code"]] = (float(row["Latitude"]), float(row["Longitude"]))
    return geo


def main():
    cells = load_notebook()
    names = parse_neighborhood_order(cells)
    venues = parse_top_venues(cells)
    idx_cluster, idx_borough = parse_clusters(cells)
    geo = load_geo()

    # Cross-check the postcode alignment against cell 42's head() output.
    assert POSTCODES[:5] == ["M4E", "M4K", "M4L", "M4M", "M4N"]
    assert len(POSTCODES) == 38

    venue_cols = [f"{n}_Most_Common_Venue" for n in
                  ["1st", "2nd", "3rd", "4th", "5th", "6th", "7th", "8th", "9th", "10th"]]
    header = (["Postcode", "Borough", "Neighborhood", "Latitude", "Longitude",
               "Cluster"] + venue_cols)

    rows, records = [], []
    for idx, name in enumerate(names):
        postcode = POSTCODES[idx]
        lat, lng = geo[postcode]
        vlist = venues[name]
        top = [v for v, _ in vlist]
        top += [""] * (10 - len(top))
        rows.append([postcode, idx_borough[idx], name, lat, lng,
                     idx_cluster[idx]] + top[:10])
        records.append({
            "postcode": postcode,
            "borough": idx_borough[idx],
            "neighborhood": name,
            "lat": lat,
            "lng": lng,
            "cluster": idx_cluster[idx],
            "venues": [{"name": v, "freq": f} for v, f in vlist],
        })

    with open(OUT, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)

    OUT_JSON.write_text(json.dumps(records, indent=2))

    print(f"Wrote {len(rows)} neighborhoods to {OUT.relative_to(ROOT)}")
    print(f"Wrote JSON payload to {OUT_JSON.relative_to(ROOT)}")
    from collections import Counter
    print("Cluster sizes:", dict(sorted(Counter(r[5] for r in rows).items())))


if __name__ == "__main__":
    main()
